bool reference_operation_kind(std::string_view kind) noexcept {return std::find(std::begin(kinds),std::end(kinds),kind)!=std::end(kinds);}
std::span<const ParameterDescriptor> reference_operation_parameters(std::string_view kind) noexcept {return reference_operation_kind(kind)?std::span<const ParameterDescriptor>(fields):std::span<const ParameterDescriptor>{};}
signal_contracts::Status reference_operation_output_contracts(const ConfiguredProcessingNode& n,const signal_contracts::NumericContract&,std::vector<OwnedProcessingContract>& out) noexcept {
    if(!reference_operation_kind(n.kind) || n.inputs.empty() || n.outputs.empty())return signal_contracts::Status::incompatible_contract;
    std::vector<OwnedProcessingContract> next;next.reserve(n.outputs.size());
    for(std::size_t i=0;i<n.outputs.size();++i){if(n.outputs[i].id!=i || !n.outputs[i].contract)return signal_contracts::Status::incompatible_contract;next.push_back(n.outputs[i].contract);}
    out=std::move(next);return signal_contracts::Status::ok;
}
